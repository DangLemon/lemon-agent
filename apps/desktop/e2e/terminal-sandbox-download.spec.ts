import fs from 'node:fs'
import path from 'node:path'

import type { ElectronApplication } from '@playwright/test'

import {
  buildAppEnv,
  createSandbox,
  launchDesktop,
  waitForAppReady,
  writeEnvFile,
  writeMockProviderConfig
} from './fixtures'
import { startMockServer } from './mock-server'
import { expect, test } from './test'

const PROMPT = 'E2E_TERMINAL_SANDBOX_DOWNLOAD create a workbook'
const CONTENT = 'generated by terminal'

test('downloads a terminal output returned as a sandbox link', async () => {
  test.setTimeout(180_000)

  const sandbox = createSandbox('terminal-sandbox-download')
  const outputName = 'terminal-generated.xlsx'
  const outputPath = path.join(sandbox.root, outputName)
  const downloadedPath = path.join(sandbox.root, 'downloaded-terminal-generated.xlsx')
  let mock: Awaited<ReturnType<typeof startMockServer>> | undefined
  let app: ElectronApplication | undefined

  try {
    mock = await startMockServer({
      toolCallPrompt: PROMPT,
      toolCallAdvertisedTools: ['terminal'],
      toolCallScript: [
        {
          name: 'terminal',
          args: {
            command: `printf ${JSON.stringify(CONTENT)} > ${outputName}`,
            output_files: [outputName]
          }
        }
      ],
      toolCallResultTools: ['terminal'],
      toolCallFinalSandboxPath: true
    })
    writeMockProviderConfig(
      sandbox.lemonHome,
      mock.url,
      undefined,
      `agent:\n  project:\n    root: ${JSON.stringify(sandbox.root)}\nterminal:\n  cwd: ${JSON.stringify(sandbox.root)}`
    )
    writeEnvFile(sandbox.lemonHome)

    const launched = await launchDesktop(buildAppEnv(sandbox))
    app = launched.app
    const { page } = launched
    await waitForAppReady({ app, page, sandbox, cleanup: async () => undefined }, 90_000)

    const composer = page.locator('[data-slot="composer-root"] [contenteditable="true"]').first()
    await composer.fill(PROMPT)
    await page.keyboard.press('Enter')

    await expect(page.getByText(outputName)).toBeVisible({ timeout: 90_000 })
    await expect(page.getByText('[blocked]', { exact: true })).toHaveCount(0)
    await app.evaluate(({ dialog }, targetPath) => {
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: targetPath })
    }, downloadedPath)
    await page.getByRole('button', { name: 'Download', description: 'Download' }).click()
    await expect.poll(() => fs.existsSync(downloadedPath), { timeout: 30_000 }).toBe(true)
    expect(fs.readFileSync(downloadedPath, 'utf8')).toBe(CONTENT)
  } finally {
    await app?.close().catch(() => undefined)
    await mock?.close()
    sandbox.cleanup()
  }
})
